import { DROP_BUCKET, getSupabase } from "../lib/drop.mjs";

const escapeHtml = (value) => String(value ?? "").replace(/[&<>"']/g, (char) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;",
})[char]);

export async function handler(event) {
  const match = event.path.match(/^\/post(\d+)\/?$/);
  if (!match) return { statusCode: 404, body: "Not found" };
  try {
    const supabase = getSupabase();
    const { data, error } = await supabase
      .from("drop_deliveries")
      .select("number, drop_submissions(display_name), drop_delivery_files(original_name, storage_path, byte_size)")
      .eq("number", Number(match[1]))
      .maybeSingle();
    if (error) throw error;
    if (!data || !data.drop_delivery_files?.length) {
      return { statusCode: 404, body: "This edited photo is not available." };
    }
    const files = [];
    for (const file of data.drop_delivery_files) {
      const signed = await supabase.storage.from(DROP_BUCKET).createSignedUrl(file.storage_path, 900, {
        download: file.original_name,
      });
      if (signed.error) throw signed.error;
      files.push({ ...file, url: signed.data.signedUrl });
    }
    const name = escapeHtml(data.drop_submissions?.display_name || "you");
    const fileMarkup = files.map((file, index) => `
      <a class="download" href="${escapeHtml(file.url)}">
        <span><b>${files.length === 1 ? "Your edited photo" : `Edited photo ${index + 1}`}</b>
        <small>${escapeHtml(file.original_name)} · full quality</small></span><strong>Download ↓</strong>
      </a>`).join("");
    return {
      statusCode: 200,
      headers: {
        "content-type": "text/html; charset=utf-8",
        "cache-control": "no-store",
        "x-robots-tag": "noindex, nofollow",
      },
      body: `<!doctype html><html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">
      <title>Your edit — Charlie Stimac</title><style>
      :root{color-scheme:dark;font-family:Inter,system-ui,sans-serif}*{box-sizing:border-box}body{margin:0;min-height:100vh;display:grid;place-items:center;padding:24px;background:radial-gradient(circle at 50% 10%,#1d2912,transparent 35rem),#050505;color:#f5f5f5}
      main{width:min(570px,100%);padding:clamp(28px,6vw,52px);border:1px solid #ffffff1c;border-radius:26px;background:#0c0c0ced;box-shadow:0 30px 100px #0008}
      .logo{width:48px;height:48px;object-fit:contain}.kicker{margin:28px 0 10px;color:#d6ff3f;font-size:.7rem;font-weight:800;letter-spacing:.18em}h1{margin:0;font-size:clamp(2.5rem,9vw,4.7rem);line-height:.94;letter-spacing:-.065em}p{color:#ffffff8f;line-height:1.6}
      .files{display:grid;gap:10px;margin-top:30px}.download{display:flex;align-items:center;justify-content:space-between;gap:20px;padding:16px;border:1px solid #ffffff1c;border-radius:13px;background:#080808;color:#fff;text-decoration:none}.download:hover{border-color:#d6ff3f}.download b,.download small{display:block}.download small{margin-top:5px;color:#ffffff62;font-size:.69rem}.download strong{color:#d6ff3f;font-size:.72rem;white-space:nowrap}
      footer{margin-top:27px;color:#ffffff4f;font-size:.68rem}</style></head><body><main>
      <img class="logo" src="/CSLOGO.png" alt=""><p class="kicker">EDIT COMPLETE</p><h1>This one's for ${name}.</h1>
      <p>Thanks for joining the live. Download your finished photo below in its full exported quality.</p>
      <div class="files">${fileMarkup}</div><footer>Link generated by Charlie Stimac · Downloads expire after 15 minutes; refresh the page if needed.</footer>
      </main></body></html>`,
    };
  } catch (error) {
    console.error("drop-delivery", error);
    return { statusCode: 500, body: "This download is temporarily unavailable." };
  }
}
